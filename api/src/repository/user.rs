use chrono::Utc;
use sqlx::{PgPool, postgres::PgQueryResult};
use uuid::Uuid;

use crate::{
    schema::{
        pagination::{Page, PageQuery},
        user::{InviteInfo, NewUser, Role, UpdateUser, User},
    },
    utils::hash_password,
};

impl User {
    /// Search matches the full name or email
    pub async fn find_page(pool: &PgPool, query: &PageQuery) -> Result<Page<User>, sqlx::Error> {
        let pattern = query.pattern();

        let users = sqlx::query_as!(
            User,
            r#"
                SELECT
                    id,
                    first_name,
                    last_name,
                    email,
                    password,
                    avatar,
                    student_id,
                    role AS "role: Role",
                    created_at,
                    updated_at
                FROM users
                WHERE $1::TEXT IS NULL
                    OR (first_name || ' ' || last_name) ILIKE $1
                    OR email ILIKE $1
                ORDER BY last_name, first_name, id
                LIMIT $2 OFFSET $3
            "#,
            pattern,
            query.per_page(),
            query.offset()
        )
        .fetch_all(pool)
        .await?;

        let total = sqlx::query_scalar!(
            r#"
                SELECT COUNT(*) AS "total!"
                FROM users
                WHERE $1::TEXT IS NULL
                    OR (first_name || ' ' || last_name) ILIKE $1
                    OR email ILIKE $1
            "#,
            pattern
        )
        .fetch_one(pool)
        .await?;

        Ok(Page::new(users, total, query))
    }

    pub async fn new(pool: &PgPool, new_user: NewUser) -> Result<User, sqlx::Error> {
        //TODO: need to handle the creation by token generated by student for role = user, only superadmin can create admins
        let user_pasword = hash_password(new_user.password.as_str()).unwrap();
        let user = User {
            id: Uuid::new_v4(),
            first_name: new_user.first_name,
            last_name: new_user.last_name,
            email: new_user.email,
            password: user_pasword,
            avatar: new_user.avatar,
            student_id: None,
            role: new_user.role,
            created_at: Utc::now(),
            updated_at: Utc::now(),
        };

        sqlx::query_as!(
            User,
            r#"
                INSERT INTO users
                    (
                        id,
                        first_name,
                        last_name,
                        email,
                        password,
                        avatar,
                        role,
                        created_at,
                        updated_at
                    )
                VALUES
                    ($1, $2, $3, $4, $5, $6, $7, $8, $9)
                RETURNING
                    id,
                    first_name,
                    last_name,
                    email,
                    avatar,
                    password,
                    student_id,
                    role AS "role: Role",
                    created_at,
                    updated_at
            "#,
            user.id,
            user.first_name,
            user.last_name,
            user.email,
            user.password,
            user.avatar,
            user.role as Role,
            user.created_at,
            user.updated_at
        )
        .fetch_one(pool)
        .await
    }

    pub async fn get_by_id(pool: &PgPool, id: Uuid) -> Result<User, sqlx::Error> {
        sqlx::query_as!(
            User,
            r#"
                SELECT
                    id,
                    first_name,
                    last_name,
                    email,
                    password,
                    avatar,
                    student_id,
                    role AS "role: Role",
                    created_at,
                    updated_at
                FROM users
                WHERE id = $1
            "#,
            id
        )
        .fetch_one(pool)
        .await
    }

    pub async fn update(
        pool: &PgPool,
        id: Uuid,
        user_to_update: UpdateUser,
    ) -> Result<UpdateUser, sqlx::Error> {
        sqlx::query_as!(
            UpdateUser,
            r#"
                UPDATE
                    users
                    SET
                        first_name = COALESCE($1, first_name),
                        last_name = COALESCE($2, last_name),
                        email = COALESCE($3, email),
                        password = COALESCE($4, password),
                        avatar = COALESCE($5, avatar),
                        role = COALESCE($6, role)
                WHERE id = $7
                RETURNING
                    first_name,
                    last_name,
                    email,
                    password,
                    avatar,
                    role AS "role: Role"
            "#,
            user_to_update.first_name,
            user_to_update.last_name,
            user_to_update.email,
            user_to_update.password,
            user_to_update.avatar,
            user_to_update.role as Option<Role>,
            id
        )
        .fetch_one(pool)
        .await
    }

    pub async fn delete(pool: &PgPool, id: Uuid) -> Result<PgQueryResult, sqlx::Error> {
        sqlx::query!("DELETE FROM users WHERE id = $1", id)
            .execute(pool)
            .await
    }

    pub async fn find_by_email(pool: &PgPool, email: String) -> Result<User, sqlx::Error> {
        sqlx::query_as!(
            User,
            r#"
                SELECT
                    id,
                    first_name,
                    last_name,
                    email,
                    password,
                    avatar,
                    student_id,
                    role AS "role: Role",
                    created_at,
                    updated_at
                FROM users
                WHERE email = $1
            "#,
            email
        )
        .fetch_one(pool)
        .await
    }

    /// The student behind an unused, unexpired invite token
    pub async fn find_invite(pool: &PgPool, token: &str) -> Result<InviteInfo, sqlx::Error> {
        sqlx::query_as!(
            InviteInfo,
            r#"
                SELECT s.first_name, s.last_name, s.email AS "email!"
                FROM invite_tokens t
                JOIN students s ON s.id = t.student_id
                WHERE t.token = $1
                    AND t.used_at IS NULL
                    AND t.expires_at > NOW()
                    AND s.email IS NOT NULL
            "#,
            token
        )
        .fetch_one(pool)
        .await
    }

    /// Creates the student's own User account and burns the invite, in one transaction.
    /// RowNotFound when the token is unknown, used or expired.
    pub async fn register_from_invite(
        pool: &PgPool,
        token: &str,
        password_hash: String,
    ) -> Result<User, sqlx::Error> {
        let mut tx = pool.begin().await?;

        // FOR UPDATE: two submits of the same link can't both create an account
        let invite = sqlx::query!(
            r#"
                SELECT t.id, s.id AS student_id, s.first_name, s.last_name, s.email AS "email!"
                FROM invite_tokens t
                JOIN students s ON s.id = t.student_id
                WHERE t.token = $1
                    AND t.used_at IS NULL
                    AND t.expires_at > NOW()
                    AND s.email IS NOT NULL
                FOR UPDATE OF t
            "#,
            token
        )
        .fetch_one(&mut *tx)
        .await?;

        let user = sqlx::query_as!(
            User,
            r#"
                INSERT INTO users
                    (id, first_name, last_name, email, password, avatar, role, student_id, status)
                VALUES
                    ($1, $2, $3, $4, $5, '', $6, $7, 'active')
                RETURNING
                    id,
                    first_name,
                    last_name,
                    email,
                    password,
                    avatar,
                    student_id,
                    role AS "role: Role",
                    created_at,
                    updated_at
            "#,
            Uuid::new_v4(),
            invite.first_name,
            invite.last_name,
            invite.email,
            password_hash,
            Role::User as Role,
            invite.student_id
        )
        .fetch_one(&mut *tx)
        .await?;

        sqlx::query!(
            "UPDATE invite_tokens SET used_at = NOW() WHERE id = $1",
            invite.id
        )
        .execute(&mut *tx)
        .await?;

        tx.commit().await?;
        Ok(user)
    }
}
